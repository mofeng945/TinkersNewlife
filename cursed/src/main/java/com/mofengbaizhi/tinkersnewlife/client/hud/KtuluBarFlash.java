    private static volatile long start = -10000L;

    private KtuluBarFlash() {
    }

    /** \u2605\u6bcf\u6b21\u62e6\u622a\u90fd\u8c03\u8fd9\u91cc \u21d2 \u2605\u91cd\u65b0\u8d77\u4e00\u6b21\u8109\u51b2 \u2713 */
